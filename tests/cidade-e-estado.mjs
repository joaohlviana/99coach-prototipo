// Seletor de cidade: Todo o Brasil, estado inteiro, limpar cidade e endereço com estado (?uf=).
const { chromium } = (await import('node:module')).createRequire('/')(process.env.PW);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 860 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message.slice(0, 200)));
const txt = (sel) => p.evaluate((s) => { const e = document.querySelector(s); return e ? e.innerText.replace(/\s+/g, ' ').trim() : ''; }, sel);
const path = () => p.url().replace('http://localhost:5173', '');
await p.goto('http://localhost:5173/treinadores/yoga/londrina-pr', { waitUntil: 'load' });
await p.waitForTimeout(2500);
let t = await txt('#app .vf-hsearch');
console.log('1 topo com rótulos e limpar:', /MODALIDADE Yoga/i.test(t), /ONDE Londrina/i.test(t), !!(await p.$('#app .vf-hclr')));
await p.click('#app .vf-hsearch .vf-hsb--city');
await p.waitForTimeout(600);
console.log('2 seletor: Todo o Brasil primeiro e estados:', /^Todo o Brasil/.test(await txt('.cs-row')), (await p.$$('.cs-ufs .chip')).length > 3);
const pr = await p.$('.cs-ufs .chip[title="Paraná"]');
if (pr) await pr.click();
await p.waitForTimeout(500);
const rows = await p.evaluate(() => [...document.querySelectorAll('.cs-row')].map((e) => e.innerText.replace(/\s+/g, ' ').trim()));
console.log('3 estado filtra as cidades:', /Paraná · estado todo/.test(rows[1] || ''), rows.slice(2).every((r) => /, PR /.test(r)), rows.length > 3);
await p.evaluate(() => { const r = [...document.querySelectorAll('.cs-row')].find((e) => /estado todo/.test(e.innerText)); if (r) r.click(); });
await p.waitForTimeout(1500);
console.log('4 estado inteiro:', path() === '/treinadores/yoga?uf=pr', /NO PARANÁ/i.test(await txt('#app h1')), /ONDE Paraná/i.test(await txt('#app .vf-hsearch')));
const cidades = await p.evaluate(() => [...document.querySelectorAll('#app .vf-tc .vf-meta')].map((e) => e.innerText).filter((x) => /, [A-Z]{2}/.test(x)));
console.log('  só profissionais do estado:', cidades.length > 0 && cidades.every((x) => /, PR/.test(x)));
await p.click('#app .vf-hclr');
await p.waitForTimeout(1500);
console.log('5 limpar cidade:', path() === '/treinadores/yoga', /^TREINADORES DE YOGA$/i.test(await txt('#app h1')), /ONDE Todo o Brasil/i.test(await txt('#app .vf-hsearch')), !(await p.$('#app .vf-hclr')));
await p.goto('http://localhost:5173/treinadores/yoga?uf=pr', { waitUntil: 'load' });
await p.waitForTimeout(2500);
console.log('6 endereço com estado abre no estado:', /NO PARANÁ/i.test(await txt('#app h1')));
console.log('errs', errs);
await b.close();
